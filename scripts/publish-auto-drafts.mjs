/**
 * Publica automáticamente el borrador que scripts/generate-blog-post.mjs
 * creó HOY (autoDate === hoy), pero SOLO si nadie lo ha tocado desde
 * entonces (ni desde el panel /admin ni de ninguna otra forma): se mira
 * el historial de git del fichero y, si solo hay el commit original del
 * bot, se le quita draft y se publica. Si hay más commits, se deja como
 * borrador para que el usuario decida cuándo publicarlo.
 *
 * Uso (lo llama .github/workflows/auto-blog-publish.yml a mediodía):
 *   node scripts/publish-auto-drafts.mjs
 *
 * Importante: el workflow debe hacer el checkout con fetch-depth: 0
 * (historial completo), si no, git log siempre verá solo 1 commit.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import matter from "gray-matter";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const BLOG_DIR = join(ROOT, "content", "blog");
const today = new Date().toISOString().slice(0, 10); // YYYY-MM-DD

let files = [];
try {
  files = readdirSync(BLOG_DIR).filter((f) => f.endsWith(".md"));
} catch {
  console.log("No existe content/blog — nada que hacer.");
  process.exit(0);
}

function commitCount(relPath) {
  try {
    const out = execFileSync("git", ["log", "--format=%H", "--", relPath], {
      cwd: ROOT,
      encoding: "utf8",
    });
    return out.split("\n").filter(Boolean).length;
  } catch {
    return -1; // no se pudo comprobar: mejor no tocar el fichero
  }
}

let published = 0;
for (const f of files) {
  const fullPath = join(BLOG_DIR, f);
  const relPath = `content/blog/${f}`;
  let parsed;
  try {
    parsed = matter(readFileSync(fullPath, "utf8"));
  } catch (e) {
    console.warn(`No se pudo leer ${f}:`, e.message);
    continue;
  }
  const { data, content } = parsed;
  if (!data.autoGenerated || !data.draft || data.autoDate !== today) continue;

  const commits = commitCount(relPath);
  if (commits === 1) {
    const newData = { ...data, draft: false };
    writeFileSync(fullPath, matter.stringify(content, newData));
    console.log(`Publicado automáticamente (sin cambios desde las 8:00): ${f}`);
    published++;
  } else if (commits > 1) {
    console.log(`Se dejó como borrador (editado a mano): ${f}`);
  } else {
    console.log(`No se pudo comprobar el historial de ${f} — se deja como borrador.`);
  }
}

if (!published) console.log("No había ningún borrador automático de hoy pendiente de publicar.");
